"""report.md for the zero-report prioritizer: plain-words summary, method, results tables, sample output, limits.

Every number and every comparison word below is computed from metrics; nothing is typed in by hand.
"""

from __future__ import annotations

import numpy as np
import pandas as pd

from .. import config
from .score import COMPONENTS, LABELS

MAIN = "Model B · zero-report prioritizer"
BASELINES = ["Model A v2 alone", "Zero-streak length (baseline)", "Historical mean, 26 weeks (baseline)", "Old Model B rule (fixed)"]
EXTRA = ["Equal weights (untuned reference)", "Supervised GBM on real swap labels (experiment)"]


def f(x, d=3, pct=False):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "—"
    return f"{100 * x:.1f}%" if pct else f"{x:.{d}f}"


def table(rows: list[list], head: list[str]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def set_table(res: dict, k: int = 5) -> str:
    rows = []
    for m in [MAIN] + BASELINES + EXTRA:
        r = res["methods"][m]
        hb = r["high_band"]
        wk = next(w for w in r["weekly_budget"] if w["k_per_week"] == k)
        rows.append([m, f(r["auc"]), f(r["average_precision"]), f(hb["recall"], pct=True), f(hb["precision"], pct=True),
                     f(hb["false_alert_rate"], pct=True), f(hb["weeks_to_detect"], 2), f(wk["recall"], pct=True), f(wk["precision"], pct=True)])
    return table(rows, ["method", "AUC", "average precision", "recall (High)", "precision (High)", "false alerts (High)",
                        "weeks to detect", f"recall, top {k}/week", f"precision, top {k}/week"])


def word(a, b):
    return "higher than" if a > b + 1e-9 else ("lower than" if a < b - 1e-9 else "the same as")


def write(path, model, results, ranked, gbm_info, manifest, figs, diag) -> None:
    R = results["Real 2020 (test): swapped zeros"]
    S = results["Synthetic 2020 (test): injected zeros"]
    G = results["Synthetic 2020 (test): regional gap entered as zero"]
    T = results["Real 2016-2017 (tuning, in-sample): swapped zeros"]
    Y = results["Synthetic 2019 (tuning): injected zeros"]
    mR, mS = R["methods"][MAIN], S["methods"][MAIN]
    best_b = max(BASELINES, key=lambda m: R["methods"][m]["average_precision"])
    best_bs = max(BASELINES, key=lambda m: S["methods"][m]["average_precision"])
    k5 = lambda r: next(w for w in r["weekly_budget"] if w["k_per_week"] == 5)
    ci = mR.get("high_band_ci", {})
    used = [k for k in COMPONENTS if model.weights[k] > 0]
    sel = model.meta["selection"]
    cal = R.get("calibration", {}).get(MAIN, {})
    z20 = ranked[ranked.priority_score.notna()]
    bands = z20.priority.value_counts().reindex(["High", "Medium", "Low"], fill_value=0)

    L = []
    L.append("# Model B · zero-report prioritizer (dengue)\n")
    L.append(f"Generated by `python -m iris_pipeline zero-priority` · run `{manifest['run_id']}` · Model A v2 run `{manifest['model_a']['run_id']}` "
             f"· runtime {manifest['runtime_s']:.0f} s. Real and synthetic results are reported separately throughout.\n")
    L.append("## In plain words\n")
    L.append(f"- **What it does.** Every explicit zero-case dengue report gets a 0-100 priority score, a High / Medium / Low band, a calibrated "
             f"share of comparable reports expected to be wrong, the indicators behind the ranking, data warnings and verification steps. "
             f"Missing reports are kept apart: they are certain gaps for the planner, never treated as zeros.")
    L.append(f"- **What it learned to use.** Tuning chose {len(used)} indicator(s): " + ", ".join(f"*{LABELS[k]}*" for k in used) +
             f". Among {sel['n_within_tolerance']:,} near-equivalent settings the simplest was kept (pre-registered rule).")
    L.append(f"- **Real data, 2020 (held-out test).** Among {R['zero_reports']:,} zero reports, {R['positives']} are known swapped reports. "
             f"Model B's average precision is {f(mR['average_precision'])}, {word(mR['average_precision'], R['methods'][best_b]['average_precision'])} "
             f"the best simple baseline ({best_b}, {f(R['methods'][best_b]['average_precision'])}). "
             f"Checking the top 5 zero reports a week reaches {f(k5(mR)['recall'], pct=True)} of the swaps "
             f"(best baseline {f(k5(R['methods'][best_b])['recall'], pct=True)}). "
             f"The High band catches {f(mR['high_band']['recall'], pct=True)} (95% CI {f(ci.get('recall_ci', (np.nan,))[0], pct=True)}–{f(ci.get('recall_ci', (np.nan, np.nan))[1], pct=True)}) "
             f"while flagging {f(mR['high_band']['false_alert_rate'], pct=True)} of normal zeros.")
    n19, n20 = diag["normal_zeros"]["2019"], diag["normal_zeros"]["2020"]
    orc5 = next(w for w in R["oracle_weekly_budget"] if w["k_per_week"] == 5)
    L.append(f"- **The bands do not transfer to 2020.** The High cut was set so {f(n19['share_above_high_cut'], pct=True)} of 2019's normal zeros "
             f"exceed it; {f(n20['share_above_high_cut'], pct=True)} of 2020's do. During COVID-19, other places in the same region were also zero "
             f"for {f(n20['mean_region_other_zero_share'], pct=True)} of normal zeros on average ({f(n19['mean_region_other_zero_share'], pct=True)} in 2019), "
             "so the regional indicator lifts many genuine zeros. Use the within-week rank, and re-set the bands on recent data before relying on them.")
    L.append(f"- **A weekly budget hits a ceiling on these labels.** All {R['positives']} real 2020 swaps fall in {diag['swaps_2020']['weeks_with_swaps']} weeks "
             f"(up to {diag['swaps_2020']['max_swaps_in_a_week']} in one week), so verifying 5 zero reports a week can reach at most "
             f"{f(orc5['recall'], pct=True)} of them even with perfect knowledge; most methods reach close to that, which is why they tie.")
    if mS["average_precision"] < S["methods"]["Model A v2 alone"]["average_precision"]:
        L.append(f"- **Trade-off.** On isolated synthetic failures Model A v2 alone ranks better ({f(S['methods']['Model A v2 alone']['average_precision'])} vs "
                 f"{f(mS['average_precision'])}): the regional indicator helps with region-wide errors (swaps, regional gaps) and hurts with isolated ones. "
                 "Show both: Model B's rank for zero reports, and Model A's p_low for single-place drops.")
    L.append("- **'Normal' is not 'verified correct'.** A zero counts as normal when it is not a known swap. Some 2020 'false alerts' may be real "
             "problems nobody labelled (late 2020 has weeks where half the country reported zero).")
    L.append(f"- **Synthetic failures injected into 2020.** Average precision {f(mS['average_precision'])} vs {f(S['methods'][best_bs]['average_precision'])} for the best baseline "
             f"({best_bs}); High-band recall {f(mS['high_band']['recall'], pct=True)}. Regional gaps entered as zero: High-band recall "
             f"{f(G['methods'][MAIN]['high_band']['recall'], pct=True)}.")
    if cal:
        L.append(f"- **Calibration.** On real 2020 zeros the model predicts {f(cal['mean_predicted'], pct=True)} bad zeros on average; "
                 f"{f(cal['observed_share'], pct=True)} were swaps (Brier {f(cal['brier'])}). The probability assumes the 2016-2018 share of swapped "
                 f"zeros ({f(model.calibration['real_share'], pct=True)}); it is an estimate under that assumption, not a guarantee.")
    L.append("- **Every alert is a lead to verify.** The data has no testing, timeliness or submission records, so IRIS cannot say why a zero "
             "happened; a high score means 'check this first', not 'this is a reporting failure'.\n")

    L.append("## Approach and why it fits the data\n")
    L.append("- **Data.** HDX/DOH dengue, 126 provinces and cities, weekly 2016-01-10 to 2021-01-10, read through the pipeline's clean table "
             f"(`{manifest['inputs']['dengue_table']}`, checked against the cleaning plan's expected counts). Fields: location, region, week, "
             "cases, report status. Explicit zeros and missing weeks are distinct. No testing volume, timeliness, submission status or real "
             "neighbour data exists; deaths are not an input.")
    L.append("- **Labels.** There are no verified labels of reporting failures. The only real labels for zero reports are the cleaning plan's "
             "swapped cases/deaths rows (2016: 196, 2017: 174 zeros; 2018-2019: none; 2020: 157). They mark one source error, so they are used "
             "for tuning and testing, not as a general definition of failure. Synthetic failures come from the pipeline's injection file.")
    L.append("- **Model.** A transparent weighted score, not a black box: no supervised model is deployed, because the available labels cover "
             "one error type and the tuning year has none. A gradient-boosting model trained on the real swaps is reported as an experiment.")
    L.append(f"- **Indicators** (past weeks only, except same-week regional context): {', '.join(LABELS[k] for k in COMPONENTS)}. "
             "Each is mapped to 0-1 with fixed, documented anchors (config.ZERO_PRIORITY).")
    L.append(f"- **Tuning (before 2020 was scored).** Grid of {sel['grid_size']:,} settings (history window, minimum history, streak criterion, "
             f"weights 0/1/2). Objective: mean average precision on synthetic 2019 ({sel['synthetic_2019']['positives']} injected zeros vs "
             f"{sel['synthetic_2019']['negatives']} real normal zeros) and real 2016-2017 ({sel['real_2016_2017']['positives']} swaps vs "
             f"{sel['real_2016_2017']['negatives']} normal zeros). Chosen objective {f(sel['chosen']['objective'])} (best {f(sel['best_objective'])}; "
             f"equal weights {f(sel['equal_weights']['objective'])}). Weights: " + ", ".join(f"{LABELS[k]} {model.weights[k]}" for k in COMPONENTS) + ".")
    unused = [p for p, k in (("history window", "rare_zero"), ("minimum history", "rare_zero"), ("streak criterion", "streak")) if model.weights[k] == 0]
    if unused:
        L.append(f"  The {', '.join(sorted(set(unused)))} only affect indicators with weight 0, so their chosen values "
                 f"({model.hist_weeks} weeks, {model.min_hist} reports, {model.streak_saturation} zeros) have no effect on scores.")
    L.append(f"- **Bands.** High: score above {f(model.bands['High'], 1)}; Medium: above {f(model.bands['Medium'], 1)}. Set so that at most "
             f"{int(100 * config.ZERO_PRIORITY['BAND_FAR']['High'])}% / {int(100 * config.ZERO_PRIORITY['BAND_FAR']['Medium'])}% of real 2019 normal zero reports "
             f"({model.meta['negatives_for_bands']}) fall in High / at least Medium. Every compared method gets its own threshold by the same rule.")
    L.append(f"- **Probability (`p_priority`).** Isotonic regression of the score on the 2019 tuning rows, prior-shifted from the tuning share "
             f"({f(model.calibration['train_share'], pct=True)}) to the real 2016-2018 share of swapped zeros ({f(model.calibration['real_share'], pct=True)}); "
             f"{len(model.calibration['bootstrap'])} bootstrap refits give the {int(100 * config.ZERO_PRIORITY['PROB_INTERVAL'])}% interval.\n")

    L.append("## Results\n")
    L.append("Thresholds were frozen before 2020 was scored. 95% intervals: cluster bootstrap over locations. 'weeks to detect' counts from the "
             "first week of an episode (real swaps: location-year; synthetic: injected event).\n")
    for title, res, note in (
        ("Real data · 2020 held-out test · swapped zero reports", R, "COVID-19 year: genuine drops and reporting interruptions both occurred."),
        ("Synthetic · 2020 held-out test · failures injected as zeros", S, "Injected into real 2020 data; the truth is known exactly."),
        ("Synthetic · 2020 held-out test · a missing regional week entered as zero", G, "The real 15 Nov 2020 regional gap, filled with zeros."),
        ("Real data · 2016-2017 · in-sample (used for tuning)", T, "Not an independent test."),
        ("Synthetic · 2019 · in-sample (used for tuning)", Y, "Not an independent test."),
    ):
        L.append(f"### {title}\n")
        L.append(f"{res['zero_reports']:,} zero reports · {res['positives']} positives · {res['negatives']} normal · positive share {f(res['positive_share'], pct=True)}. {note}\n")
        L.append(set_table(res) + "\n")
    L.append("### Limited investigation budget (real 2020)\n")
    rows = []
    for m in [MAIN] + BASELINES + EXTRA:
        rows.append([m] + [f"{f(w['recall'], pct=True)} / {f(w['precision'], pct=True)}" for w in R["methods"][m]["weekly_budget"]])
    rows.append(["*Ceiling (knows the answers)*"] + [f"{f(w['recall'], pct=True)} / {f(w['precision'], pct=True)}" for w in R["oracle_weekly_budget"]])
    L.append(table(rows, ["method"] + [f"top {k}/week: recall / precision" for k in config.ZERO_PRIORITY["WEEKLY_BUDGETS"]]) + "\n")
    if cal:
        L.append("### Calibration of p_priority on real labels\n")
        for key in ("Real 2016-2017 (tuning, in-sample): swapped zeros", "Real 2020 (test): swapped zeros"):
            c = results[key]["calibration"][MAIN]
            L.append(f"**{key}** · Brier {f(c['brier'])} · mean predicted {f(c['mean_predicted'], pct=True)} · observed {f(c['observed_share'], pct=True)}\n")
            L.append(table([[r["bin"], r["n"], f(r["mean_predicted"], pct=True), f(r["observed_share"], pct=True)] for r in c["reliability"]],
                           ["p_priority bin", "zero reports", "mean predicted", "observed share"]) + "\n")
    L.append("### Supervised experiment (real swap labels only)\n")
    L.append(f"Gradient boosting, forward chaining: fit on 2016, hyperparameters chosen on 2017 (average precision {f(gbm_info['validation_ap_2017'])}, "
             f"{gbm_info['grid_size']} settings), refit on 2016-2018 ({gbm_info['train_rows']} zeros, {gbm_info['train_positives']} swaps). Chosen: "
             + ", ".join(f"{k} {v}" for k, v in gbm_info["chosen"].items()) +
             ". It learns the swap pattern only and is not the deployed model; its rows in the tables above are the comparison.\n")

    L.append("## Sample output for the IRIS dashboard\n")
    wk = figs["sample_week"]
    s = ranked[(ranked.week_start.astype(str) == wk) & ranked.priority_score.notna()].head(10)
    rows = [[int(r.rank_in_week), str(r.location).title(), r.priority, f(r.priority_score, 1),
             f"{f(r.p_priority, pct=True)} ({f(r.p_priority_low, pct=True)}–{f(r.p_priority_high, pct=True)})", r.data_sufficiency,
             str(r.explanation)] for r in s.itertuples()]
    L.append(f"Week of {wk} (real data). Full file: `outputs/zero_priority/ranked_alerts_2020.csv` "
             f"({len(z20):,} zero reports in 2020: High {bands['High']}, Medium {bands['Medium']}, Low {bands['Low']}). "
             "Each row also carries data warnings and verification steps.\n")
    L.append(table(rows, ["rank", "location", "priority", "score", "p_priority (90% interval)", "data", "why"]) + "\n")
    top = s.iloc[0] if len(s) else None
    if top is not None:
        L.append(f"Verification steps for rank 1: {top.verification_steps}\n")
        L.append(f"Data warnings for rank 1: {top.data_warnings}\n")

    L.append("## Figures\n")
    for name, cap in (("1_priority_list_week.png", "Ranked zero reports for one week, with each indicator's contribution"),
                      ("2_contributing_indicators.png", "Main contributing indicators for High and Medium alerts, 2020"),
                      ("3_weekly_budget_recall.png", "Share of bad zeros reached at each weekly verification budget (real vs synthetic)"),
                      ("4_calibration.png", "Calibration of p_priority on real swap labels"),
                      ("5_weekly_priority_counts.png", "Zero reports by priority band each week, 2020")):
        L.append(f"![{cap}](figures/{name})\n\n*{cap}.*\n")

    L.append("## Limitations and assumptions\n")
    for t in [
        "No verified labels of reporting failures exist. Swapped cases/deaths rows are real but are one error type; results on them do not show "
        "how the model ranks other real failures (for example a facility that stopped reporting but sends zeros).",
        "The tuning year (2019) has no real bad zeros, so tuning mixes synthetic 2019 failures with real 2016-2017 swaps; 2016-2017 results are in-sample.",
        "Synthetic failures follow the pipeline's injection design (zero-fill, outage, regional outage); real failures may look different.",
        "No testing, timeliness or submission metadata: the cause of a zero cannot be determined, and a genuine absence of cases cannot be ruled out.",
        "Regional context uses region membership only. No real adjacency or reporting-network data exists, so no graph model is used.",
        "2020 is a COVID-19 year: consultations genuinely fell, so more zeros are real and false alerts are expected to be higher.",
        "p_priority assumes the 2016-2018 share of swapped zeros; if the true share differs, the probabilities shift (the ranking does not).",
        "Province/city weekly counts only; facility-level problems that do not change a province's total are invisible.",
    ]:
        L.append(f"- {t}")
    L.append("\n## Integration with Model A and the planner\n")
    for t in [
        "**Input contract.** Model B reads Model A v2's `scores_v2.csv` (dengue rows, `report_status`, `cases`, `expected`, `p_low`, `region_id`, `hub_id`) "
        "plus the shared calendar and locations. `api.prepare_history()` maps the contract to the indicator frame; `api.rank_alerts()` returns the ranked list.",
        "**Candidates.** Explicit zeros (`report_status = reported`, `cases = 0`). Missing weeks are returned as 'Missing report (not ranked)'.",
        "**Order of steps.** Model A scores a week → Model B ranks that week's zero reports → the Model B v2 planner can use `p_priority` for zero rows "
        "when choosing `call_location` actions (the planner code is unchanged here).",
        "**History.** Ranking a week needs that location's previous two years of Model A scores for the full set of indicators.",
        "**Re-tuning.** Re-run `python -m iris_pipeline zero-priority` after Model A changes; `model.json` holds every learned value as plain JSON.",
    ]:
        L.append(f"- {t}")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
