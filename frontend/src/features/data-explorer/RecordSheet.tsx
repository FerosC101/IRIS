import * as D from "@radix-ui/react-dialog";
import { useQuery } from "@tanstack/react-query";
import { SlotStatusBadge } from "@/components/data-display/badges";
import { SheetContent } from "@/components/ui/dialog";
import { KeyValue } from "@/components/ui/panel";
import { ErrorState, Loading } from "@/components/ui/states";
import { useSession } from "@/hooks/useSession";
import { fmtDateTime, fmtPeriod } from "@/lib/format";
import { VALUE_STATUS } from "@/lib/labels";
import { api } from "@/services/api";
import type { RecordRow } from "@/types/api";

export function RecordSheet({ datasetId, row, onClose }: { datasetId: string; row: RecordRow | null; onClose: () => void }) {
  const { categoryName } = useSession();
  const rid = row?.record_id ?? null;
  const q = useQuery({ queryKey: ["record", datasetId, rid], queryFn: () => api.record(datasetId, rid!), enabled: rid !== null });
  return (
    <D.Root open={!!row} onOpenChange={(o) => !o && onClose()}>
      {row && (
        <SheetContent title={rid ? `Record ${rid}` : "Expected report — not received"} description={`${row.unit_name ?? row.area ?? "—"} · ${categoryName(row.category_code)} · ${fmtPeriod(row.period_start, row.period_end)}`}>
          <div className="flex flex-col gap-5 p-5">
            {rid === null ? (
              <>
                <SlotStatusBadge status="not_received" />
                <p className="text-sm text-ink">This report was expected by the reporting schedule but no record has been received. It is <strong>not</strong> the same as a zero report.</p>
                <KeyValue columns={1} items={[{ label: "Due", value: fmtDateTime(row.due_at) }, { label: "Frequency", value: row.frequency ?? "—" }]} />
              </>
            ) : q.error ? <ErrorState error={q.error} /> : !q.data ? <Loading /> : (
              <>
                <KeyValue items={[
                  { label: "Reporting unit", value: q.data.unit?.name ?? "Not specified" },
                  { label: "Area", value: q.data.area ?? "—" },
                  { label: "Category", value: categoryName(q.data.category_code) },
                  { label: "Period", value: fmtPeriod(q.data.period_start, q.data.period_end) },
                  { label: "Value", value: q.data.value_status === "blank" ? "Blank (not reported)" : String(q.data.value) },
                  { label: "Value status", value: VALUE_STATUS[q.data.value_status].label },
                  { label: "Due", value: fmtDateTime(q.data.due_at) },
                  { label: "Received", value: fmtDateTime(q.data.received_at) },
                  { label: "Timeliness", value: q.data.status ? <SlotStatusBadge status={q.data.status} /> : "Not calculable (no timestamps)" },
                  { label: "Form completeness", value: q.data.fields_complete === null ? "Not recorded" : `${Math.round(q.data.fields_complete * 100)}% of required fields` },
                  { label: "Revision", value: String(q.data.revision) },
                  { label: "Source row", value: q.data.source_row ? `Row ${q.data.source_row} of the imported file` : "Generated by simulator" },
                ]} />
                {q.data.note && <div><p className="text-xs text-ink-2">Note</p><p className="text-sm">{q.data.note}</p></div>}
                <div>
                  <h3 className="mb-1.5 text-sm font-semibold">Change history</h3>
                  {q.data.history.length === 0 ? <p className="text-sm text-ink-2">No changes since the record was created.</p> : (
                    <ul className="flex flex-col gap-2 text-sm">{q.data.history.map((h, i) => <li key={i}><p>{h.summary}</p><p className="text-xs text-ink-2">{fmtDateTime(h.at)}</p></li>)}</ul>
                  )}
                </div>
              </>
            )}
          </div>
        </SheetContent>
      )}
    </D.Root>
  );
}
