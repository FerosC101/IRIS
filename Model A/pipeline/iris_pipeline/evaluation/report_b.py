        f"{ob.iloc[0]['recall at 1% budget (2020 swaps)']:.0%} of them with "
        f"{ob.iloc[0]['false-alert rate (2020 normal weeks)']:.1%} false alerts, more than Model A v2 "
        f"({ob.loc['Model A v2', 'recall at 1% budget (2020 swaps)']:.0%} at "
        f"{ob.loc['Model A v2', 'false-alert rate (2020 normal weeks)']:.1%}). Model A v2 still ranks zeros better "
