        f"{ff['recovered submissions'][0]:.0f} for fixing facilities one by one (the proposal's baseline): "
        f"{na['recovered per staff-hour'][0]:.2f} vs {ff['recovered per staff-hour'][0]:.2f} per staff-hour. "
