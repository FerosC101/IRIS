B_DIR = OUT_DIR / "model_b"


def fmt(v, pct=False, dec=3):
    if isinstance(v, tuple):
        m, lo, hi = v
        if np.isnan(m):
            return ""
        f = (lambda x: f"{x:.0%}") if pct else (lambda x: f"{x:.{dec}f}")
        return f"{f(m)} ({f(lo)}–{f(hi)})" if not np.isnan(lo) else f(m)
    return v


def table(df: pd.DataFrame, pct_cols=(), dec=3) -> pd.DataFrame:
    out = df.copy()
    for c in out.columns:
        out[c] = out[c].map(lambda v: fmt(v, c in pct_cols, dec))
    return out


def _m(df, method, col):
    return df.set_index(df.columns[0]).loc[method, col][0]


def figures(net: dict, rec_sum: pd.DataFrame, old_b: pd.DataFrame) -> list[str]:
    fig_dir = B_DIR / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    names = []

    def save(fig, name):
        fig.tight_layout()
        fig.savefig(fig_dir / name, dpi=130)
        plt.close(fig)
        names.append(name)

    s = net["summary"]
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.6))
    for ax, col, title in zip(axes, ["hub source identified", "lab source identified", "facility-week recall"],
                              ["Hub failures: right hub named", "Lab failures: right lab named", "Failing facility-weeks flagged"]):
        m = np.array([v[0] for v in s[col]])
        lo = np.array([v[1] for v in s[col]])
        hi = np.array([v[2] for v in s[col]])
        y = np.arange(len(s))
        ax.barh(y, m, xerr=[np.nan_to_num(m - lo), np.nan_to_num(hi - m)], color=["#bbbbbb", "#999999", "#6baed6", "#1f77b4"])
        ax.set_yticks(y, s.method if ax is axes[0] else [""] * len(y), fontsize=8)
        ax.set_xlim(0, 1)
        ax.set_title(title, fontsize=10)
    fig.suptitle("Graph ablation (simulated, 20 replicates, 95% intervals)", fontsize=11)
    save(fig, "1_graph_ablation.png")

    r = rec_sum[rec_sum["staff hours / week"] == config.PLAN["STAFF_HOURS_PER_WEEK"]]
    r = r[r.policy != "No action"]
    fig, ax = plt.subplots(figsize=(8, 3.4))
    m = np.array([v[0] for v in r["recovered submissions"]])
    lo = np.array([v[1] for v in r["recovered submissions"]])
    hi = np.array([v[2] for v in r["recovered submissions"]])
    colors = ["#1f77b4" if "Network" in p else ("#cccccc" if "Oracle" in p else "#c0504d") for p in r.policy]
    ax.barh(r.policy, m, xerr=[m - lo, hi - m], color=colors)
    ax.set_xlabel("failed facility-weeks avoided vs no action (per simulated year)")
    ax.set_title(f"Recovered submissions, {config.PLAN['STAFF_HOURS_PER_WEEK']:.0f} staff-hours per week")
    save(fig, "2_policy_recovered.png")

    fig, ax = plt.subplots(figsize=(6, 3.6))
    for pol, color in (("Network-aware (Model B v2)", "#1f77b4"), ("Facility-first (proposal baseline)", "#c0504d")):
        g = rec_sum[rec_sum.policy == pol].sort_values("staff hours / week")
        ax.errorbar(g["staff hours / week"], [v[0] for v in g["recovered submissions"]],
                    yerr=[[v[0] - v[1] for v in g["recovered submissions"]], [v[2] - v[0] for v in g["recovered submissions"]]],
                    marker="o", color=color, label=pol, capsize=3)
    ax.set_xlabel("staff hours per week")
    ax.set_ylabel("recovered submissions")
    ax.set_title("Staff budget sensitivity")
    ax.legend(fontsize=8)
    save(fig, "3_hours_sensitivity.png")
    return names


